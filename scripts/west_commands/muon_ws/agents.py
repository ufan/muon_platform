"""Generated agent files for all AI coding tools (ADR-009 §14).

Canonical, committed sources:
  rules   AGENTS.md (every repo; hub AGENTS.md for platform-wide rules)
  skills  platform/.agents/skills/<skill>/SKILL.md (Agent Skills open standard)

Generated here (never edited by hand, git-ignored in projects):
  workspace root  AGENTS.md (hub rules + catalog), CLAUDE.md / GEMINI.md shims,
                  .agents/skills/muon-* and .claude/skills/muon-* links
  each project    .agents/skills/muon-* and .claude/skills/muon-* links
                  (Codex only scans up to the git root, Claude only .claude/skills),
                  tool-native L3 adapters (read access to legacy refs, writes denied)
"""

import json
import os

from . import refs as refs_mod
from .catalog import catalog_rows, markdown_table

GENERATED_MARKER = "<!-- generated by `west agents-sync`; edit platform/AGENTS.md instead -->"
SHIM = "@AGENTS.md\n"
SKILL_PREFIX = "muon-"
SKILL_DIRS = (".agents/skills", ".claude/skills")
GITIGNORE_HEADER = "# west agents-sync generated agent files (ADR-009 §14)"
GITIGNORE_LINES = ["/.agents/skills/muon-*", "/.claude/skills/muon-*", "/.claude/settings.local.json"]
DEV_MATURITIES = ("incubating", "active", "stable")
# ---------------------------------------------------------------- sources
def hub_source(ws):
    """The hub checkout providing AGENTS.md and .agents/skills, or None (e.g. a repo-rooted
    workspace whose manifest does not list `platform`)."""
    return ws.hub_dir()


def skill_names(hub):
    sd = os.path.join(hub, ".agents", "skills")
    return sorted(n for n in os.listdir(sd)
                  if n.startswith(SKILL_PREFIX) and os.path.isfile(os.path.join(sd, n, "SKILL.md")))


def test_data_root(ws):
    """Test data bytes (ADR-011): MUON_DATA_ROOT, else <testdata project>/golden when present."""
    root = os.environ.get("MUON_DATA_ROOT")
    if root:
        return os.path.abspath(root)
    td = ws.get("testdata")
    if td and os.path.isdir(os.path.join(td.abspath, "golden")):
        return os.path.join(td.abspath, "golden")
    return None


# ---------------------------------------------------------------- actions
class Plan:
    """Desired state, applied or checked as a whole."""

    def __init__(self):
        self.items = []      # (kind, path, value)
        self.notes = []

    def file(self, path, content, protect_handwritten=False):
        self.items.append(("file", path, (content, protect_handwritten)))

    def link(self, path, target):
        self.items.append(("link", path, target))

    def prune_links(self, directory, keep):
        self.items.append(("prune", directory, set(keep)))

    def claude_settings(self, path, dirs, denied, managed):
        self.items.append(("claude", path, (dirs, denied, managed)))

    def gitignore(self, path):
        self.items.append(("gitignore", path, None))


def _rel(target, link_path):
    return os.path.relpath(target, os.path.dirname(link_path))


def _link_target(src, link_path, topdir):
    inside = os.path.commonpath([os.path.abspath(src), topdir]) == topdir
    return _rel(src, link_path) if inside else src


def build_plan(ws, hub):
    plan = Plan()
    skills = skill_names(hub) if hub else []
    skill_src = os.path.join(hub, ".agents", "skills") if hub else None

    def skill_links(base):
        for sd in SKILL_DIRS:
            d = os.path.join(base, sd)
            for s in skills:
                lp = os.path.join(d, s)
                plan.link(lp, _link_target(os.path.join(skill_src, s), lp, ws.topdir))
            plan.prune_links(d, skills)

    # Workspace root.
    if hub:
        with open(os.path.join(hub, "AGENTS.md"), encoding="utf-8") as f:
            rules = f.read().rstrip() + "\n"
        rows = catalog_rows(ws, ws.members())
        plan.file(os.path.join(ws.topdir, "AGENTS.md"), "\n".join([
            GENERATED_MARKER, "", rules,
            "## Workspace catalog (generated from the west manifest)", "",
            markdown_table(rows), ""]), protect_handwritten=True)
    else:
        plan.notes.append("hub (`platform`) not in this workspace: root AGENTS.md and skill links not generated")
    plan.file(os.path.join(ws.topdir, "CLAUDE.md"), SHIM)
    plan.file(os.path.join(ws.topdir, "GEMINI.md"), SHIM)
    skill_links(ws.topdir)

    legacy_paths = [p.abspath for p in ws.legacy_projects()]
    contracts = ws.get("contracts")
    data_root = test_data_root(ws)
    # Per-project files only in projects under active development; `reference` and `legacy`
    # projects are modified only on explicit request (ADR-009 §5).
    # In a repo-rooted workspace the manifest repo (e.g. daq) is the project under development.
    targets = [m for m in ws.members() if m.cloned and (m.maturity in DEV_MATURITIES or m.is_manifest)]
    for p in targets:
        skill_links(p.abspath)
        refs = [r for r in ws.legacy_refs_for([p.name]) if r.cloned]
        dirs = [r.abspath for r in refs]
        if contracts and contracts.cloned and contracts.name != p.name:
            dirs.append(contracts.abspath)
        denied = [f"{tool}(/{r.abspath}/**)" for r in refs for tool in ("Edit", "Write")]
        if data_root and p.name != "testdata":
            dirs.append(data_root)
            denied += [f"{tool}(/{data_root}/**)" for tool in ("Edit", "Write")]
        managed = legacy_paths + ([contracts.abspath] if contracts else []) + ([data_root] if data_root else [])
        plan.claude_settings(os.path.join(p.abspath, ".claude", "settings.local.json"), dirs, denied, managed)
        plan.gitignore(os.path.join(p.abspath, ".gitignore"))
        for f in ("AGENTS.md",):
            if not os.path.isfile(os.path.join(p.abspath, f)):
                plan.notes.append(f"{p.name}: no {f} (rules for all tools); see platform/templates/project/")
        for shim in ("CLAUDE.md", "GEMINI.md"):
            sp = os.path.join(p.abspath, shim)
            if not os.path.isfile(sp) or "@AGENTS.md" not in open(sp, encoding="utf-8").read():
                plan.notes.append(f"{p.name}: {shim} missing or does not import @AGENTS.md")
        for r in ws.legacy_refs_for([p.name]):
            if not r.cloned:
                plan.notes.append(f"{p.name}: legacy ref {r.name} not cloned (run `west refs sync`)")
            elif not refs_mod.status(r.abspath)["locked"]:
                plan.notes.append(f"STALE {r.name}: legacy checkout is not locked (run `west refs sync`)")
    return plan


# ---------------------------------------------------------------- apply / check
def _claude_merge(path, dirs, denied, managed):
    data = {}
    if os.path.isfile(path):
        with open(path, encoding="utf-8") as f:
            data = json.load(f)
    if not dirs and not denied and not os.path.isfile(path):
        return None
    perms = data.setdefault("permissions", {})

    def is_managed(entry):
        return any(m and m in entry for m in managed)

    perms["additionalDirectories"] = [d for d in perms.get("additionalDirectories", []) if not is_managed(d)] + dirs
    perms["deny"] = [d for d in perms.get("deny", []) if not is_managed(d)] + denied
    for k in ("additionalDirectories", "deny"):
        if not perms[k]:
            del perms[k]
    return json.dumps(data, indent=2) + "\n"


def _gitignore_content(path):
    old = open(path, encoding="utf-8").read() if os.path.isfile(path) else ""
    lines = old.splitlines()
    missing = [l for l in GITIGNORE_LINES if l not in lines]
    if not missing:
        return old
    block = ([GITIGNORE_HEADER] if GITIGNORE_HEADER not in lines else []) + missing
    return old.rstrip("\n") + ("\n\n" if old.strip() else "") + "\n".join(block) + "\n"


def run(plan, check=False, force=False, log=print):
    """Apply (or check) the plan. Returns the list of stale paths."""
    stale = []
    for kind, path, value in plan.items:
        if kind == "file":
            content, protect = value
            old = open(path, encoding="utf-8").read() if os.path.isfile(path) else None
            if old == content:
                continue
            stale.append(path)
            if check:
                continue
            if protect and old is not None and "edit platform/AGENTS.md instead -->" not in old:
                if not force:
                    raise RuntimeError(f"{path} is hand-written; rerun with --force to replace it (kept as .orig)")
                os.replace(path, path + ".orig")
            with open(path, "w", encoding="utf-8") as f:
                f.write(content)
            log(f"  wrote {path}")
        elif kind == "link":
            if os.path.islink(path) and os.readlink(path) == value:
                continue
            stale.append(path)
            if check:
                continue
            parent = os.path.dirname(path)
            if os.path.islink(parent):           # migrate an old whole-directory link
                os.remove(parent)
            os.makedirs(parent, exist_ok=True)
            if os.path.lexists(path):
                if not os.path.islink(path):
                    raise RuntimeError(f"{path} exists and is not a link; move it away first")
                os.remove(path)
            os.symlink(value, path)
            log(f"  linked {path} -> {value}")
        elif kind == "prune":
            if not os.path.isdir(path) or os.path.islink(path):
                continue
            for n in os.listdir(path):
                lp = os.path.join(path, n)
                if n.startswith(SKILL_PREFIX) and os.path.islink(lp) and n not in value:
                    stale.append(lp)
                    if not check:
                        os.remove(lp)
                        log(f"  removed stale link {lp}")
        elif kind == "claude":
            new = _claude_merge(path, *value)
            if new is None:
                continue
            old = open(path, encoding="utf-8").read() if os.path.isfile(path) else None
            if old is not None and json.loads(old) == json.loads(new):
                continue
            stale.append(path)
            if check:
                continue
            os.makedirs(os.path.dirname(path), exist_ok=True)
            with open(path, "w", encoding="utf-8") as f:
                f.write(new)
            log(f"  wrote {path} (claude adapter: legacy read access, writes denied)")
        elif kind == "gitignore":
            new = _gitignore_content(path)
            old = open(path, encoding="utf-8").read() if os.path.isfile(path) else ""
            if new == old:
                continue
            stale.append(path)
            if not check:
                with open(path, "w", encoding="utf-8") as f:
                    f.write(new)
                log(f"  updated {path} (not committed; review and commit)")
    for n in plan.notes:
        log(f"  note: {n}")
        if n.startswith("STALE"):
            stale.append(n)
    return stale


