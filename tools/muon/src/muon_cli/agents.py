"""Generated agent files for all AI coding tools (`muon agents sync`; ADR-009 §14, ADR-012).

Canonical, committed sources:
  rules   AGENTS.md (every repo; platform/AGENTS.md for workspace-wide rules)
  skills  platform/.agents/skills/<skill>/SKILL.md (Agent Skills open standard)

Generated here (never edited by hand, git-ignored in repos):
  workspace root  AGENTS.md (platform rules + repo map), CLAUDE.md / GEMINI.md shims,
                  .agents/skills/muon-* and .claude/skills/muon-* links
  each dev repo   .agents/skills/muon-* and .claude/skills/muon-* links
                  (Codex only scans up to the git root, Claude only .claude/skills),
                  tool-native adapters (sibling repos readable, legacy and golden data write-denied)
"""

import json
import os

from . import legacy as legacy_mod

GENERATED_MARKER = "<!-- generated by `muon agents sync`; edit platform/AGENTS.md instead -->"
SHIM = "@AGENTS.md\n"
SKILL_PREFIX = "muon-"
SKILL_DIRS = (".agents/skills", ".claude/skills")
GITIGNORE_HEADER = "# muon agents sync: generated agent files (ADR-012)"
OLD_GITIGNORE_HEADER = "# west agents-sync generated agent files (ADR-009 §14)"
GITIGNORE_LINES = ["/.agents/skills/muon-*", "/.claude/skills/muon-*", "/.claude/settings.local.json",
                   "/.claude/.muon-adapter.json"]
MAP_COLUMNS = ["path", "maturity", "role", "spec", "informs"]


# ---------------------------------------------------------------- sources
def skill_names(hub):
    sd = os.path.join(hub, ".agents", "skills")
    return sorted(n for n in os.listdir(sd)
                  if n.startswith(SKILL_PREFIX) and os.path.isfile(os.path.join(sd, n, "SKILL.md")))


def test_data_root(ws):
    """Test data bytes (ADR-011): MUON_DATA_ROOT, else <testdata>/golden when present."""
    root = os.environ.get("MUON_DATA_ROOT")
    if root:
        return os.path.abspath(root)
    td = ws.get("testdata")
    if td and os.path.isdir(os.path.join(td.abspath, "golden")):
        return os.path.join(td.abspath, "golden")
    return None


def repo_map(ws):
    lines = ["| " + " | ".join(MAP_COLUMNS) + " |", "|" + "|".join("---" for _ in MAP_COLUMNS) + "|"]
    for r in sorted(ws.repos, key=lambda r: (r.is_legacy, r.path)):
        row = {"path": f"`{r.path}`", "maturity": r.maturity, "role": r.meta.get("role", ""),
               "spec": f"`{r.meta['spec']}`" if r.meta.get("spec") else "",
               "informs": ", ".join(r.informs)}
        lines.append("| " + " | ".join(str(row[c]) for c in MAP_COLUMNS) + " |")
    return "\n".join(lines)


# ---------------------------------------------------------------- plan
class Plan:
    """Desired state, applied or checked as a whole."""

    def __init__(self):
        self.items = []      # (kind, path, value)
        self.notes = []

    def file(self, path, content, protect_handwritten=False):
        self.items.append(("file", path, (content, protect_handwritten)))

    def link(self, path, target):
        self.items.append(("link", path, target))

    def prune_links(self, directory, keep):
        self.items.append(("prune", directory, set(keep)))

    def claude_settings(self, path, dirs, denied, managed):
        self.items.append(("claude", path, (dirs, denied, managed)))

    def gitignore(self, path, lines):
        self.items.append(("gitignore", path, lines))


def _link_target(src, link_path, topdir):
    inside = os.path.commonpath([os.path.abspath(src), topdir]) == topdir
    return os.path.relpath(src, os.path.dirname(link_path)) if inside else src


def build_plan(ws):
    plan = Plan()
    hub = ws.hub_dir()
    skills = skill_names(hub) if hub else []
    skill_src = os.path.join(hub, ".agents", "skills") if hub else None

    def skill_links(base):
        for sd in SKILL_DIRS:
            d = os.path.join(base, sd)
            for s in skills:
                lp = os.path.join(d, s)
                plan.link(lp, _link_target(os.path.join(skill_src, s), lp, ws.topdir))
            plan.prune_links(d, skills)

    # Workspace root.
    if hub:
        with open(os.path.join(hub, "AGENTS.md"), encoding="utf-8") as f:
            rules = f.read().rstrip() + "\n"
        plan.file(os.path.join(ws.topdir, "AGENTS.md"), "\n".join([
            GENERATED_MARKER, "", rules,
            "## Repository map (generated from platform/repos)", "",
            repo_map(ws), ""]), protect_handwritten=True)
    else:
        plan.notes.append("platform is not cloned: root AGENTS.md and skill links not generated")
    plan.file(os.path.join(ws.topdir, "CLAUDE.md"), SHIM)
    plan.file(os.path.join(ws.topdir, "GEMINI.md"), SHIM)
    skill_links(ws.topdir)

    legacy_paths = [r.abspath for r in ws.legacy_repos()]
    data_root = test_data_root(ws)
    siblings = [r for r in ws.repos if not r.is_legacy and r.cloned]
    # Per-repo files only in repos under development; `support` and `legacy` repos are
    # modified only on explicit request (ADR-009 §5).
    for r in [m for m in ws.repos if m.cloned and (m.is_dev or m.path == "platform")]:
        if r.path != "platform":                 # the skills' source; its .claude/skills is a committed link
            skill_links(r.abspath)
        refs = [x for x in ws.legacy_informing([r.name]) if x.cloned]
        dirs = [x.abspath for x in refs] + [s.abspath for s in siblings if s is not r]
        # Claude Code: an Edit(path) rule covers every file-writing tool; Write(path) never matches.
        denied = [f"Edit(/{x.abspath}/**)" for x in refs]
        if data_root and r.name != "testdata":
            dirs.append(data_root)
            denied.append(f"Edit(/{data_root}/**)")
        managed = legacy_paths + [s.abspath for s in siblings] + ([data_root] if data_root else [])
        plan.claude_settings(os.path.join(r.abspath, ".claude", "settings.local.json"), dirs, denied, managed)
        # platform holds the canonical skills in .agents/skills: never ignore them there.
        lines = GITIGNORE_LINES if r.path != "platform" else [l for l in GITIGNORE_LINES if "/skills/" not in l]
        plan.gitignore(os.path.join(r.abspath, ".gitignore"), lines)
        if not os.path.isfile(os.path.join(r.abspath, "AGENTS.md")):
            plan.notes.append(f"{r.path}: no AGENTS.md; see platform/templates/project/")
        for shim in ("CLAUDE.md", "GEMINI.md"):
            sp = os.path.join(r.abspath, shim)
            if not os.path.isfile(sp) or "@AGENTS.md" not in open(sp, encoding="utf-8").read():
                plan.notes.append(f"{r.path}: {shim} missing or does not import @AGENTS.md")
        for x in ws.legacy_informing([r.name]):
            if not x.cloned:
                plan.notes.append(f"{r.path}: legacy repo {x.path} not cloned (run `muon ws sync --legacy`)")
            elif not legacy_mod.status(x.abspath)["locked"]:
                plan.notes.append(f"STALE {x.path}: legacy checkout is not locked (run `muon ws sync`)")
    return plan


# ---------------------------------------------------------------- apply / check
CLAUDE_RECORD = ".muon-adapter.json"     # entries muon wrote last time, next to settings.local.json


def _claude_record_path(path):
    return os.path.join(os.path.dirname(path), CLAUDE_RECORD)


def _claude_merge(path, dirs, denied, managed):
    data = {}
    if os.path.isfile(path):
        with open(path, encoding="utf-8") as f:
            data = json.load(f)
    if not dirs and not denied and not os.path.isfile(path):
        return None
    perms = data.setdefault("permissions", {})
    previous = set()
    rec = _claude_record_path(path)
    if os.path.isfile(rec):
        with open(rec, encoding="utf-8") as f:
            previous = set(json.load(f).get("entries", []))

    def is_managed(entry):
        # Entries muon wrote before (even for a workspace that has since moved) or for current paths.
        return entry in previous or any(m and m in entry for m in managed)

    perms["additionalDirectories"] = [d for d in perms.get("additionalDirectories", []) if not is_managed(d)] + dirs
    perms["deny"] = [d for d in perms.get("deny", []) if not is_managed(d)] + denied
    for k in ("additionalDirectories", "deny"):
        if not perms[k]:
            del perms[k]
    return json.dumps(data, indent=2) + "\n"


def _gitignore_content(path, wanted):
    old = open(path, encoding="utf-8").read() if os.path.isfile(path) else ""
    lines = [GITIGNORE_HEADER if l == OLD_GITIGNORE_HEADER else l for l in old.splitlines()]
    missing = [l for l in wanted if l not in lines]
    if not missing and lines == old.splitlines():
        return old
    block = ([GITIGNORE_HEADER] if GITIGNORE_HEADER not in lines else []) + missing
    body = "\n".join(lines).rstrip("\n")
    if block:
        body += ("\n\n" if body.strip() else "") + "\n".join(block)
    return body + "\n"


def run(plan, check=False, force=False, log=print):
    """Apply (or check) the plan. Returns the list of stale paths."""
    stale = []
    for kind, path, value in plan.items:
        if kind == "file":
            content, protect = value
            old = open(path, encoding="utf-8").read() if os.path.isfile(path) else None
            if old == content:
                continue
            stale.append(path)
            if check:
                continue
            if protect and old is not None and "edit platform/AGENTS.md instead -->" not in old:
                if not force:
                    raise RuntimeError(f"{path} is hand-written; rerun with --force to replace it (kept as .orig)")
                os.replace(path, path + ".orig")
            with open(path, "w", encoding="utf-8") as f:
                f.write(content)
            log(f"  wrote {path}")
        elif kind == "link":
            if os.path.islink(path) and os.readlink(path) == value:
                continue
            stale.append(path)
            if check:
                continue
            parent = os.path.dirname(path)
            if os.path.islink(parent):           # migrate an old whole-directory link
                os.remove(parent)
            os.makedirs(parent, exist_ok=True)
            if os.path.lexists(path):
                if not os.path.islink(path):
                    raise RuntimeError(f"{path} exists and is not a link; move it away first")
                os.remove(path)
            os.symlink(value, path)
            log(f"  linked {path} -> {value}")
        elif kind == "prune":
            if not os.path.isdir(path) or os.path.islink(path):
                continue
            for n in os.listdir(path):
                lp = os.path.join(path, n)
                if n.startswith(SKILL_PREFIX) and os.path.islink(lp) and n not in value:
                    stale.append(lp)
                    if not check:
                        os.remove(lp)
                        log(f"  removed stale link {lp}")
        elif kind == "claude":
            new = _claude_merge(path, *value)
            if new is None:
                continue
            old = open(path, encoding="utf-8").read() if os.path.isfile(path) else None
            if old is not None and json.loads(old) == json.loads(new):
                continue
            stale.append(path)
            if check:
                continue
            os.makedirs(os.path.dirname(path), exist_ok=True)
            with open(path, "w", encoding="utf-8") as f:
                f.write(new)
            with open(_claude_record_path(path), "w", encoding="utf-8") as f:
                json.dump({"entries": value[0] + value[1]}, f, indent=2)
            log(f"  wrote {path} (claude adapter: sibling repos readable, legacy/golden writes denied)")
        elif kind == "gitignore":
            new = _gitignore_content(path, value)
            old = open(path, encoding="utf-8").read() if os.path.isfile(path) else ""
            if new == old:
                continue
            stale.append(path)
            if not check:
                with open(path, "w", encoding="utf-8") as f:
                    f.write(new)
                log(f"  updated {path} (not committed; review and commit)")
    for n in plan.notes:
        log(f"  note: {n}")
        if n.startswith("STALE"):
            stale.append(n)
    return stale


