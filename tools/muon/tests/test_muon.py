def init(tmp_path, platform, *extra):
    top = tmp_path / "ws"
    assert cli.main(["ws", "init", str(top), "--platform-url", platform, *extra]) == 0
    return top


def test_init_clones_repos_but_not_legacy_by_default(remotes, monkeypatch):
    tmp_path, platform = remotes
    top = init(tmp_path, platform)
    assert (top / "core" / ".git").exists()
    assert not (top / "legacy" / "old").exists()
    assert (top / "AGENTS.md").read_text().startswith("<!-- generated by `muon agents sync`")
    assert os.path.islink(top / "core" / ".claude" / "skills" / "muon-demo")


def test_repo_metadata_overrides_repos_file(remotes):
    tmp_path, platform = remotes
    top = init(tmp_path, platform)
    ws = Workspace(topdir=str(top))
    assert ws.get("core").meta["role"] == "from repo"
    assert ws.get("legacy/old").informs == ["core"]


