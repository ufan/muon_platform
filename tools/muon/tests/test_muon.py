def git(*args, cwd=None):
    subprocess.run(["git", *args], cwd=cwd, check=True, capture_output=True)


def make_remote(base, name, files, branch="main"):
    """Create a bare repo `<base>/remotes/<name>.git` with the given files on `branch`."""
    src = base / "src" / name
    src.mkdir(parents=True)
    git("init", "-q", "-b", branch, cwd=src)
    git("config", "user.email", "t@example.com", cwd=src)
    git("config", "user.name", "t", cwd=src)
    for rel, content in files.items():
        p = src / rel
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_text(content)
    git("add", "-A", cwd=src)
    git("commit", "-q", "-m", "init", cwd=src)
    bare = base / "remotes" / f"{name}.git"
    git("clone", "-q", "--bare", str(src), str(bare))
    return str(bare)


